  await applicant.locator("#application-message").fill("Хочу помочь с бэкендом")
  await applicant.getByRole("button", { name: "Отправить заявку" }).click()
  await expect(applicant.getByText("На рассмотрении", { exact: true })).toBeVisible()
  await owner.getByRole("button", { name: "Заявки и приглашения", exact: true }).click()
  await expect(owner.getByText("Хочу помочь с бэкендом")).toBeVisible()
  await owner.getByRole("button", { name: "Принять", exact: true }).click()
  await expect(
    owner.locator(".project-application .tag").filter({ hasText: "Принято" }),
  ).toBeVisible()
  await owner.getByRole("button", { name: "Команда (2)" }).click()
  await expect(owner.getByText("Кандидат", { exact: true })).toBeVisible()
  await expect(owner.getByText("Свободных мест: 1")).toBeVisible()
  await applicant.reload()
  await applicant.getByRole("button", { name: "Изменить", exact: true }).click()
  await applicant.locator("#contribution").fill("Реализовал API")
  await applicant.getByRole("button", { name: "Сохранить", exact: true }).click()
  await expect(applicant.getByText("Реализовал API", { exact: true })).toBeVisible()
  await applicant.getByRole("button", { name: "Команда (2)" }).click()
  applicant.once("dialog", (dialog) => dialog.accept())
  await applicant.getByRole("button", { name: "Покинуть проект" }).click()
  await expect(applicant.getByRole("button", { name: "Команда (1)" })).toBeVisible()
  await owner.reload()
