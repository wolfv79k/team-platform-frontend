  await owner.getByLabel("Требуемый уровень: TypeScript").selectOption("ADVANCED")
  await owner.locator("#form-vacancy-search").fill("Backend")
  await owner.getByRole("option", { name: "Backend", exact: true }).click()
  await owner.getByLabel("Количество мест: Backend").fill("2")
  await owner.getByRole("button", { name: "Создать проект", exact: true }).click()
  await expect(owner.getByRole("heading", { name: "Проект проверки" })).toBeVisible()
  const path = new URL(owner.url()).pathname
  await expect(owner.getByText("Продвинутый", { exact: true }).first()).toBeVisible()
  await expect(owner.getByText("Свободных мест: 2")).toBeVisible()
  await signIn(applicant, "applicant", path)
  await applicant.getByRole("button", { name: "Подать заявку", exact: true }).first().click()
