  await expect(owner.locator("#project-detail-status")).toHaveValue("ENDED")
  await expect(owner.getByText("Разработал интерфейс и сервер", { exact: true })).toBeVisible()
  await owner.getByRole("link", { name: "Редактировать" }).click()
  await expect(owner.locator("#roleId")).toHaveValue("2")
  await expect(owner.getByLabel("Количество мест: Backend")).toHaveValue("3")
  await expect(owner.locator("#partners")).toHaveValue("Партнёр A, Партнёр B")
  await owner.getByRole("link", { name: "Отмена", exact: true }).click()
  await expect(owner.locator(".project-relation-row").filter({ hasText: "React" })).toBeVisible()
  await expect(
    owner.locator(".project-relation-row").filter({ hasText: "TypeScript" }),
  ).toHaveCount(0)
  await owner.getByRole("button", { name: "Изменить стек" }).click()
  await owner.getByRole("button", { name: "Добавить TypeScript", exact: true }).click()
  await owner.getByRole("button", { name: "Сохранить стек" }).click()
  await expect(
    owner.locator(".project-relation-row").filter({ hasText: "TypeScript" }),
  ).toBeVisible()
  await owner.locator("#project-detail-status").selectOption("IN_PROGRESS")
  await expect(owner.getByText("Статус сохранён", { exact: true })).toBeVisible()
  await owner.reload()
  await expect(owner.locator("#project-detail-status")).toHaveValue("IN_PROGRESS")
